"""Round 22 UI kit: cut the painted UI atlases in src/asset/ui by their JSON guides into transparent webp pieces.

The atlases are RGB on black. Large near-black regions (and any touching the crop edge) become transparent with a soft
edge; the dark slate inside panels/slots (~RGB 30-45) stays opaque. 6.png has no guide: its pieces are found as connected
blobs and named in EXTRA below (row-major order). Output: public/art/ui-kit/<id>.webp + src/game/ui/uiKit.ts.
Usage: python3 scripts/ui/build_ui_kit.py
"""
import json, os, sys
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src/asset/ui')
OUT = os.path.join(ROOT, 'public/art/ui-kit')
TS = os.path.join(ROOT, 'src/game/ui/uiKit.ts')
GUIDES = {  # guide → atlas image (1.png = 4.png, 2.png = 5.png are duplicates)
    'ui_hud_gauges_atlas.json': ('1.png', 'sprites'),
    'ui_panels_controls_atlas.json': ('2.png', 'sprites'),
    'ui_slots_icons_atlas.json': ('3.png', 'sprites'),
    'ui_general_merchant_guide.json': ('7.png', 'items'),
    'ui_complete_menu_icons_guide.json': ('8.png', 'icons'),
}
EXTRA = ['icon_bag_grid', 'icon_equipment_armor', 'icon_potion_red', 'icon_gold_pouch', 'icon_key_e',
         'icon_portal_swirl', 'icon_search', 'icon_trash', 'icon_sort', 'icon_weight',
         'btn_auto_on', 'btn_auto_off', 'icon_refresh', 'icon_fast_forward', 'icon_key_i',
         'icon_key_ii', 'icon_star_on', 'icon_star_off', 'icon_warning', 'icon_help', 'icon_crystal_orb']
DARK = 18  # max channel value counted as the black backdrop


def key_black(rgb: np.ndarray) -> np.ndarray:
    mx = rgb.max(2)
    dark = mx <= DARK
    lab, n = ndimage.label(dark)
    h, w = dark.shape
    edge = set(np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))) - {0}
    sizes = ndimage.sum(dark, lab, range(1, n + 1))
    clear = np.zeros_like(dark)
    for i, s in enumerate(sizes, 1):
        if i in edge or s > max(400, 0.02 * h * w):
            clear |= lab == i
    alpha = np.full(dark.shape, 255.0)
    alpha[clear] = 0
    # soft rim: pixels next to the cleared backdrop fade by brightness (anti-aliased gold edges on black)
    rim = ndimage.binary_dilation(clear, iterations=2) & ~clear
    alpha[rim] = np.clip((mx[rim] - 6) / 34.0, 0, 1) * 255
    return alpha.astype(np.uint8)


def save(img: Image.Image, box, pid: str, meta: dict, kit: dict):
    crop = np.array(img.crop(box).convert('RGB'))
    a = key_black(crop)
    rgba = np.dstack([crop, a])
    Image.fromarray(rgba, 'RGBA').save(os.path.join(OUT, pid + '.webp'), 'WEBP', quality=92, method=6)
    kit[pid] = {'w': box[2] - box[0], 'h': box[3] - box[1], **meta}


def main():
    os.makedirs(OUT, exist_ok=True)
    kit = {}
    for guide, (png, key) in GUIDES.items():
        d = json.load(open(os.path.join(SRC, guide), encoding='utf-8'))
        img = Image.open(os.path.join(SRC, png))
        for s in d[key]:
            f = s['frame']
            meta = {'th': s.get('name_th', '')}
            if s.get('nine_slice'):
                meta['nine'] = [s['nine_slice'][k] for k in ('top', 'right', 'bottom', 'left')]
            save(img, (f['x'], f['y'], f['x'] + f['w'], f['y'] + f['h']), s['id'], meta, kit)
    # 6.png: no guide — connected blobs, row-major
    img = Image.open(os.path.join(SRC, '6.png')).convert('RGB')
    a = np.array(img).max(2) > DARK + 10
    lab, n = ndimage.label(ndimage.binary_closing(ndimage.binary_dilation(a, iterations=6), iterations=4))
    boxes = [sl for sl in ndimage.find_objects(lab) if (sl[0].stop - sl[0].start) > 40 and (sl[1].stop - sl[1].start) > 40]
    rows = sorted(boxes, key=lambda b: b[0].start)
    lines, cur = [], []
    for b in rows:
        if cur and b[0].start > cur[0][0].stop - 20:
            lines.append(cur); cur = []
        cur.append(b)
    if cur: lines.append(cur)
    ordered = [b for ln in lines for b in sorted(ln, key=lambda b: b[1].start)]
    if len(ordered) != len(EXTRA):
        print('6.png blobs', len(ordered), '!= names', len(EXTRA), file=sys.stderr)
    for name, b in zip(EXTRA, ordered):
        save(img, (max(0, b[1].start - 4), max(0, b[0].start - 4), b[1].stop + 4, b[0].stop + 4), name, {'th': ''}, kit)
    with open(TS, 'w', encoding='utf-8') as fh:
        fh.write('// generated by scripts/ui/build_ui_kit.py from src/asset/ui — do not edit\n')
        fh.write('export type UiPiece = { w: number; h: number; th: string; nine?: [number, number, number, number] };\n')
        fh.write('export const UI_KIT: Record<string, UiPiece> = ' + json.dumps(kit, ensure_ascii=False, indent=1) + ';\n')
        fh.write("export const uiSrc = (id: string) => `/art/ui-kit/${id}.webp`;\n")
    print('pieces', len(kit))


if __name__ == '__main__':
    main()
