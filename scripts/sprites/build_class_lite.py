"""Round 22: small login-screen atlases. The lineup only shows each class facing the camera (row S) playing idle / attack /
skill, so instead of the full 8-direction atlas (50-110 MB of GPU memory each) it loads m-<Class>-lite.webp: those
frames only, cells scaled to 0.6. Reads src/game/sprites/classAnims.ts + public/art/anim/m-<Class>.webp, writes
public/art/anim/m-<Class>-lite.webp and src/game/sprites/classLite.ts.  Usage: python3 scripts/sprites/build_class_lite.py
"""
import json, os
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TS = os.path.join(ROOT, 'src/game/sprites/classAnims.ts')
SCALE = 0.6
t = open(TS, encoding='utf-8').read(); s = t.index('{', t.index('CLASS_ANIMS')); e = t.index('\n};', s) + 2
anims = json.loads(t[s:e])
out = {}
for key, a in anims.items():
    im = Image.open(os.path.join(ROOT, f'public/art/anim/{key}.webp')).convert('RGBA')
    cw, ch, cols = a['cw'], a['ch'], a['cols']
    lw, lh = round(cw * SCALE), round(ch * SCALE)
    frames, clips = [], {}
    for name in ('idle', 'attack', 'skill'):
        if name not in a['clips']: continue
        st, n = a['clips'][name]
        clips[name] = [len(frames), n]
        for f in range(n):  # direction 0 = S (facing the camera)
            i = st + f
            frames.append(im.crop(((i % cols) * cw, (i // cols) * ch, (i % cols + 1) * cw, (i // cols + 1) * ch)).resize((lw, lh), Image.LANCZOS))
    lc = min(8, len(frames)); rows = (len(frames) + lc - 1) // lc
    atlas = Image.new('RGBA', (lc * lw, rows * lh), (0, 0, 0, 0))
    for k, fr in enumerate(frames): atlas.paste(fr, ((k % lc) * lw, (k // lc) * lh))
    atlas.save(os.path.join(ROOT, f'public/art/anim/{key}-lite.webp'), 'WEBP', quality=90, method=6)
    out[f'{key}-lite'] = {'cw': lw, 'ch': lh, 'cols': lc, 'n': len(frames), 'fx': a['fx'], 'fy': a['fy'], 'bodyPx': round(a['bodyPx'] * SCALE), 'clips': clips}
    print(key, atlas.size, clips)
with open(os.path.join(ROOT, 'src/game/sprites/classLite.ts'), 'w', encoding='utf-8') as fh:
    fh.write('// generated by scripts/sprites/build_class_lite.py — login lineup atlases (row S only, 0.6 scale). Do not edit.\n')
    fh.write("import type { SpriteAnim } from './anims';\n")
    fh.write('export const CLASS_LITE: Record<string, SpriteAnim> = ' + json.dumps(out, indent=1) + ';\n')
